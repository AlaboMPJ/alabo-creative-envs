"""Verifiers v1 entrypoint for exr_render_repair.

Generated by tools/package_for_hub.py. Do not hand-edit; regenerate instead.

WHY v1. The v0 entrypoint (vf.SingleTurnEnv, vf.Rubric) stopped existing in verifiers 0.3:
under 0.4.1 the import fails, so a Hub install of a v0 package cannot run at all. v1 is a Taskset
in, a Task out, with the reward as an async method on the Task.

The grader runs as a SUBPROCESS rather than an import, deliberately. Each one needs a different
heavy dependency, a crashed grader must not take a training run with it, and the identical code
path runs whether it is called by the container entrypoint, by a person at a terminal, or by the
RL runtime. A reward function that behaves differently under training than it does at a terminal
is the worst failure available here, and this rules it out.
"""
import glob
import json
import os
import subprocess
import sys
import tempfile

import verifiers.v1 as vf

HERE = os.path.dirname(os.path.abspath(__file__))
# NAMESPACED DATA. Four environments installed into one venv would otherwise merge their
# top-level tasks/ and tests/ directories, and every one of them would then read all four
# task sets. The wheel maps each package's data to <env_id>_tasks and <env_id>_tests.
DATA = os.path.join(HERE, "exr_render_repair" + "_tasks")
TESTS = os.path.join(HERE, "exr_render_repair" + "_tests")
INSTRUCTION = os.path.join(HERE, "exr_render_repair" + "_instruction.md")
# A source checkout has tasks/ and tests/ at the package root; an installed wheel namespaces
# them. Fall back so both work, and so a developer running from the repo sees the real tasks.
if not os.path.isdir(DATA):
    DATA = os.path.join(HERE, "tasks")
if not os.path.isdir(TESTS):
    TESTS = os.path.join(HERE, "tests")
if not os.path.exists(INSTRUCTION):
    INSTRUCTION = os.path.join(HERE, "instruction.md")
ENV_ID = "exr_render_repair"
ARTIFACT = "submission.exr"
SUMMARY = "Repair a render handoff that opens cleanly and is wrong."
ENV_DIR_ARG = True

__all__ = ["CraftTaskset"]


def _tasks():
    out = []
    for p in sorted(glob.glob(os.path.join(DATA, "*.json"))):
        name = os.path.basename(p)[:-5]
        # Exclude only the shared reference, which is prefixed. An earlier
        # version also dropped anything ending "_reference" and silently ate the
        # ocio task literally named ambiguous_reference: it loaded, errored
        # nowhere, and shipped four tasks where there were five. Video's
        # per-task references are .mp4 and never match this glob.
        if name.startswith("_"):
            continue
        with open(p) as f:
            out.append((name, p, json.load(f)))
    return out


def _payload(spec):
    """Text where the artifact is text, a description where it is binary,
    because an EXR cannot be put in a prompt."""
    if "broken_graph" in spec:
        return json.dumps(spec["broken_graph"], indent=2)
    for key in ("broken_config", "broken_file"):
        if key in spec:
            p = os.path.join(DATA, spec[key])
            if p.rsplit(".", 1)[-1] in ("exr", "mp4", "mov"):
                return (f"Binary artifact at {spec[key]}. Reported symptom: "
                        f"{spec.get('symptom', 'unknown')}")
            with open(p) as f:
                return f.read()
    return ""


def _grade(task_path, completion, artifact=None):
    grader = os.path.join(TESTS, "grader.py")
    with tempfile.TemporaryDirectory() as tmp:
        sub = os.path.join(tmp, ARTIFACT)
        if artifact is not None:
            # A BINARY ARTIFACT ARRIVES AS BYTES, NOT AS PROSE. v1 carries file outputs in
            # trace.state.artifacts; writing them here is what lets an EXR or an MP4 be graded
            # through the same subprocess as a text config.
            with open(sub, "wb") as f:
                f.write(artifact)
        else:
            text = completion if isinstance(completion, str) else str(completion)
            binary = not ARTIFACT.endswith((".json", ".ocio", ".nk", ".txt"))
            with open(sub, "wb" if binary else "w") as f:
                f.write(text.encode("latin-1", "ignore") if binary else text)
        # A grader needs its own heavy dependency and the runtime venv may not
        # have it. Running the wrong interpreter once made the OCIO grader
        # degrade to structural-only and PASS a broken config, so the override
        # is per environment.
        interp = (os.environ.get("CREATIVE_ENVS_PY_" + ENV_ID.upper())
                  or os.environ.get("CREATIVE_ENVS_PY") or sys.executable)
        try:
            cmd = [interp, grader, "--submission", sub, "--task", task_path]
            if ENV_DIR_ARG:
                cmd += ["--env-dir", HERE]
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
        except subprocess.TimeoutExpired:
            return 0.0
        if r.returncode == 2:
            # Environment error rather than a failed attempt. Raising stops the
            # run instead of silently feeding zeros to every rollout.
            raise RuntimeError(
                ENV_ID + " grader cannot run: "
                + (r.stderr or r.stdout or "").strip()[:200])
    lines = (r.stdout or r.stderr or "").strip().splitlines()
    if not lines:
        return 0.0
    try:
        return float(json.loads(lines[-1]).get("reward", 0.0))
    except json.JSONDecodeError:
        return 0.0


class CraftConfig(vf.TasksetConfig):
    """One task instance per JSON file in tasks/, minus the prefixed reference."""


class CraftData(vf.TaskData):
    task: str
    """The task file's stem, which is also the id in task.toml."""
    symptom: str = ""


class CraftTask(vf.Task[CraftData, vf.State, vf.TaskConfig]):
    @vf.reward
    async def craft_correct(self, trace) -> float:
        """Binary. Partial credit would teach that a nearly-working artifact is
        nearly right, which is false: it delivers correctly or it does not."""
        path = os.path.join(DATA, self.data.task + ".json")
        if not os.path.exists(path):
            return 0.0
        state = getattr(trace, "state", None)
        artifacts = getattr(state, "artifacts", None) or {}
        artifact = artifacts.get(ARTIFACT) if isinstance(artifacts, dict) else None
        return _grade(path, trace.last_reply or "", artifact)


class CraftTaskset(vf.Taskset[CraftTask, CraftConfig]):
    def load(self):
        instruction = ""
        p = INSTRUCTION
        if os.path.exists(p):
            with open(p) as f:
                instruction = f.read()
        for name, _path, spec in _tasks():
            yield CraftTask(
                CraftData(
                    prompt=(f"{instruction}\n\n## Task: {name}\n\n"
                            f"Reported symptom: "
                            f"{spec.get('symptom', spec.get('error', 'none'))}\n\n"
                            f"```\n{_payload(spec)}\n```\n"),
                    task=name,
                    symptom=str(spec.get("symptom", spec.get("error", ""))),
                ),
                self.config.task,
            )


def load_environment(**kwargs):
    task_config = vf.TaskConfig(
        rewards={"craft_correct": vf.RewardFunctionConfig()},
    )
    config = vf.SingleAgentEnvConfig(
        taskset=CraftConfig(id=ENV_ID, task=task_config),
        agent=vf.AgentConfig(max_turns=25),
        **kwargs,
    )
    return vf.SingleAgentEnv(config)
